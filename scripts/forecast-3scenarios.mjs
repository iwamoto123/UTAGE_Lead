// 令和8年度 通期（2026-04〜2027-03）の3段階予測
const A = { 売上: 16918554, 費用: 17252110, 営業利益: -333556 };  // 4〜8月 実績
const R7_9to3 = 3100000 + 3550000 + 4800000 + 4800000 + 4110000 + 3630000 + 1280000; // 令和7年度 9〜3月(3月は推計)
// 固定的な費用（9〜3月の7ヶ月）
const 給与 = 1135085 * 7;                       // 8月水準（給与＋法定福利費）
const 業務委託 = Math.round(522401 / 5) * 7;     // 4〜8月平均
const 家賃光熱 = Math.round(428171 / 5) * 7;     // 4〜8月平均
const 経費 = Math.round((2772365 - 364753) / 5) * 7; // 4〜8月平均（7月のCursor異常 ¥364,753 を除外）
const 固定費 = 給与 + 業務委託 + 家賃光熱 + 経費;
const バイト率 = 4033968 / 16918554;             // 4〜8月の売上比 23.8%
const 月謝平均 = 55813;

const S = [
  { name: "① 保守", 前年比: 1.15, LM月: 550000, 教材冊: 134, 短期件: 27, 教材広告: 1200000, 広告率: 0.20, upsell: 0,
    note: "月謝の前年比が1.15倍に鈍化。教材は値上げで3割減。短期プログラムは9月並み。ローカルメディは縮小" },
  { name: "② 標準", 前年比: 1.24, LM月: 700000, 教材冊: 154, 短期件: 41, 教材広告: 1200000, 広告率: 0.20, upsell: 0,
    note: "直近4ヶ月の前年比1.24倍が続く。教材は値上げで2割減。短期プログラムは計画どおり。ローカルメディは14名で損益分岐" },
  { name: "③ 強気", 前年比: 1.35, LM月: 850000, 教材冊: 192, 短期件: 50, 教材広告: 1500000, 広告率: 0.20, upsell: 0.10,
    note: "4月と同じ前年比1.35倍。教材は前年と同数を4万円で販売。教材購入者の10%がアップセルで入塾。ローカルメディ18名" },
];
const yen = (n) => "¥" + Math.round(n).toLocaleString();
console.log(`【共通の前提】9〜3月の7ヶ月`);
console.log(`  給与・法定福利費 ${yen(給与)} / 業務委託 ${yen(業務委託)} / 地代家賃・水道光熱 ${yen(家賃光熱)} / SaaS・通信・その他 ${yen(経費)}`);
console.log(`  固定的な費用 計 ${yen(固定費)} ／ バイト代は売上の ${(バイト率 * 100).toFixed(1)}% ／ 令和7年度の9〜3月 ${yen(R7_9to3)}\n`);
const out = [];
for (const s of S) {
  const 月謝 = Math.round(R7_9to3 * s.前年比);
  const LM = s.LM月 * 7;
  const 教材 = s.教材冊 * 40000;
  const 短期 = s.短期件 * 10000;
  const up = Math.round(s.教材冊 * s.upsell) * 月謝平均 * 3;   // 平均3ヶ月在籍
  const upN = Math.round(s.教材冊 * s.upsell);
  const 売上 = 月謝 + LM + 教材 + 短期 + up;
  const 月謝系 = 月謝 + LM + up;
  const バイト = Math.round(月謝系 * バイト率);
  const 広告 = Math.round(月謝系 * s.広告率) + s.教材広告;
  const 仕入 = s.教材冊 * 1500;
  const 費用 = 固定費 + バイト + 広告 + 仕入;
  const 利益 = 売上 - 費用;
  const 通期売上 = A.売上 + 売上, 通期利益 = A.営業利益 + 利益;
  out.push({ ...s, 月謝, LM, 教材, 短期, up, upN, 売上, バイト, 広告, 仕入, 費用, 利益, 通期売上, 通期利益 });
  console.log(`=========== ${s.name}（前年比 ${s.前年比}／教材 ${s.教材冊}冊） ===========`);
  console.log(`  ${s.note}`);
  console.log(`  [売上] 月謝(宮崎+白谷) ${yen(月謝)} / ローカルメディ ${yen(LM)} / 教材 ${yen(教材)} / 短期プログラム ${yen(短期)}` + (up ? ` / アップセル ${yen(up)}(${upN}名)` : ""));
  console.log(`         9〜3月 売上計 ${yen(売上)}`);
  console.log(`  [費用] 固定費 ${yen(固定費)} / バイト代 ${yen(バイト)} / 広告費 ${yen(広告)} / 教材仕入 ${yen(仕入)} → 計 ${yen(費用)}`);
  console.log(`  [利益] 9〜3月 ${yen(利益)} (${(利益 / 売上 * 100).toFixed(1)}%)`);
  console.log(`  ★通期  売上 ${yen(通期売上)} / 営業利益 ${yen(通期利益)} (${(通期利益 / 通期売上 * 100).toFixed(1)}%)\n`);
}
console.log("=========== 通期サマリー ===========");
console.log("シナリオ".padEnd(9) + "通期売上".padStart(14) + "通期営業利益".padStart(15) + "利益率".padStart(9) + "前年比(売上)".padStart(13));
for (const o of out) console.log(o.name.padEnd(9) + yen(o.通期売上).padStart(14) + yen(o.通期利益).padStart(15) + ((o.通期利益 / o.通期売上 * 100).toFixed(1) + "%").padStart(9) + ((o.通期売上 / 41250000).toFixed(2) + "倍").padStart(13));
console.log("\n【広告費を売上の25%まで広げた場合の利益】");
for (const o of out) {
  const 広告25 = Math.round((o.月謝 + o.LM + o.up) * 0.25) + o.教材広告;
  const 利益25 = o.利益 - (広告25 - o.広告);
  console.log(`  ${o.name}: ${yen(o.通期利益)} → ${yen(A.営業利益 + 利益25)}（−${yen(広告25 - o.広告)}）`);
}
